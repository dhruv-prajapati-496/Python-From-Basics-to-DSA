#endswith function: used to return boolean value if the string ends with given keywords or not.
str = "Deep Learning"
print(str.endswith("ing")) #Returns true if string ends with the given keywords.

#Capitalize Funtion : Used to capitalize 1st character of a string
str1 = "dhruv"
print(str1.capitalize())

#Replace funtion : Replaces all occurences of a value to a new one.
str2 = "I will do it myself."
print(str2.replace("l","YY"))

#Find Function: Returns 1st index of 1st occurence, works for words and letters also.
str3 = "Hardest choices requires strongest wills."
print(str3.find("will"))

#count Function: Returns the number of occurences of a keyword.
str4 = "ana is Eating Banana in canada"
print(str4.count("ana"))
