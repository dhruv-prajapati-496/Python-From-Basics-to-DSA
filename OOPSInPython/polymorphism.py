# Polymorphism : it is an object-oriented programming concept where a single interface, function, or method name can work with different types of objects, each behaving in its own appropriate way.
print(1+2) # here + works as add operator
print("Dhruv " + "Prajapati") # here it is concatinating two strings
print([1,2,3] + [4,5,6]) # here it is merging two lists. 
# This is how polymorphism can be defined. And the example is also known as operator overloading
